// ===== LAYOUT =====
// Один ответ на вопрос «мы сейчас в узкой раскладке?» для всего пульта.
//
// Зачем: строка '(max-width:900px)' была скопирована в map.js (дважды), windows.js и инлайн-скрипт
// index.html, а рядом в style.css живут её же медиазапросы. Число в JS и число в CSS — разные
// копии одной величины: поменяли брейкпоинт в стилях, забыли в скриптах — и в полосе между старым
// и новым значением вёрстка уже мобильная, а логика ещё считает экран широким. Молча и только на
// части устройств: панель карты не сворачивается, Support не уезжает в подвал, аккордеон работает
// не в том режиме.
//
// Поэтому JS вообще не знает числа: CSS внутри своего медиазапроса поднимает флаг --narrow, а
// здесь мы просто спрашиваем у браузера, поднят ли он. Разойтись физически не с чем — источник
// один, и это сам медиазапрос.
//
// Не распространяется на respect.js и radio.js: они общие с вики, где style.css пульта не
// подключён, поэтому свои стили (и свой медиазапрос) они возят с собой — это не копия, а
// автономность разделяемого модуля.
window.LHLayout = (function () {
  const root = document.documentElement;
  const narrow = () => getComputedStyle(root).getPropertyValue('--narrow').trim() === '1';

  // matchMedia тут не годится — он требует ту самую строку запроса, от которой мы и уходим.
  // Слушаем resize и сравниваем с прошлым ответом: колбэк зовётся только на смене раскладки,
  // а не на каждый пиксель перетаскивания окна.
  function onNarrowChange(fn) {
    let last = narrow();
    window.addEventListener('resize', () => {
      const now = narrow();
      if (now === last) return;
      last = now;
      fn(now);
    });
  }

  return { narrow, onNarrowChange };
})();
